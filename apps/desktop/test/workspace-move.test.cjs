const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { createLocalApi } = require('../src/local-api.cjs');
const { relocateBreakpointPaths } = require('../src/java-breakpoint-configuration.cjs');
test('path remapping preserves advanced points and exact directory boundaries', () => {
  const points = { 'src/A.java': [{ line: 4, condition: 'true', hitCondition: '3', logMessage: 'x={x}' }], 'src2/B.java': [9] };
  assert.deepEqual(relocateBreakpointPaths(points, 'src', 'renamed'), { 'renamed/A.java': points['src/A.java'], 'src2/B.java': [9] });
  assert.throws(() => relocateBreakpointPaths(points, 'src/A.java', 'A.txt'));
  assert.throws(() => relocateBreakpointPaths({ 'A.java': [1], 'B.java': [2] }, 'A.java', 'B.java'));
});
test('local file and directory moves migrate saved points and reject overwrite and unsafe paths', async t => {
  const directory = fs.mkdtempSync(path.join(os.tmpdir(), 'workspace-move-'));
  t.after(() => fs.rmSync(directory, { recursive: true, force: true }));
  const root = path.join(directory, 'project'); fs.mkdirSync(root);
  fs.mkdirSync(path.join(root, 'src')); fs.mkdirSync(path.join(root, 'dest'));
  fs.writeFileSync(path.join(root, 'src/A.java'), 'class A {}');
  fs.writeFileSync(path.join(root, 'dest/Existing.java'), 'do not overwrite');
  fs.mkdirSync(path.join(root, '.git')); fs.writeFileSync(path.join(root, '.git/config'), 'metadata');
  let available = true; let failEncrypt = false;
  const codec = { available: () => available, encrypt: value => { if (failEncrypt) throw new Error('Injected encryption failure'); return Buffer.from(value).toString('base64'); }, decrypt: value => Buffer.from(value, 'base64').toString() };
  const options = { token: 'test-token', storePath: path.join(directory, 'store.sqlite3'), credentialCodec: codec };
  let api = await createLocalApi(options);
  t.after(() => api.close()); const project = api.registerWorkspace(root);
  const headers = { Authorization: 'Bearer test-token', 'Content-Type': 'application/json' };
  let base = `${api.origin}/api/local/projects/${project.id}`;
  const request = (from, to, extra = {}) => fetch(`${base}/files`, { method: 'PATCH', headers, body: JSON.stringify({ from, to, ...extra }) });
  const point = { line: 1, condition: 'true', hitCondition: '2', logMessage: 'A' };
  let response = await request('src/A.java', 'dest/A.java', { breakpoints: { 'src/A.java': [point] } });
  assert.equal(response.status, 200); assert.deepEqual((await response.json()).breakpoints, { 'dest/A.java': [point] });
  assert.equal(fs.existsSync(path.join(root, 'src/A.java')), false);
  assert.equal(fs.readFileSync(path.join(root, 'dest/A.java'), 'utf8'), 'class A {}');
  response = await request('dest', 'moved'); assert.equal(response.status, 200);
  const saved = await (await fetch(`${base}/java-run/breakpoint-configuration`, { headers })).json();
  assert.deepEqual(saved.breakpoints, { 'moved/A.java': [point] });
  assert.equal((await request('moved/A.java', 'moved/Existing.java')).status, 409);
  assert.equal(fs.readFileSync(path.join(root, 'moved/Existing.java'), 'utf8'), 'do not overwrite');
  for (const [from, to] of [['moved', 'moved/inside'], ['moved/A.java', '../escape.java'], ['.git', 'metadata'], ['moved/A.java', '.git/A.java'], ['moved/A.java', 'A.txt']]) assert.equal((await request(from, to)).status, 400, `${from} -> ${to}`);
  fs.symlinkSync(root, path.join(root, 'alias'), 'dir');
  assert.equal((await request('alias/moved/A.java', 'A.java')).status, 400);
  assert.equal((await request('moved/A.java', 'alias/A.java')).status, 400);
  fs.symlinkSync(path.join(root, 'absent'), path.join(root, 'dangling.java'));
  assert.equal((await request('moved/A.java', 'dangling.java')).status, 409);
  assert.equal(fs.readFileSync(path.join(root, 'moved/A.java'), 'utf8'), 'class A {}');
  available = false;
  assert.equal((await request('moved/A.java', 'A.java')).status, 503);
  assert.equal(fs.existsSync(path.join(root, 'moved/A.java')), true);
  available = true; failEncrypt = true;
  assert.equal((await request('moved/A.java', 'A.java')).status, 500);
  assert.equal(fs.existsSync(path.join(root, 'moved/A.java')), true);
  assert.equal(fs.existsSync(path.join(root, 'A.java')), false);
  failEncrypt = false;
  await api.close(); api = await createLocalApi(options); api.registerWorkspace(root);
  base = `${api.origin}/api/local/projects/${project.id}`;
  assert.deepEqual((await (await fetch(`${base}/java-run/breakpoint-configuration`, { headers })).json()).breakpoints, { 'moved/A.java': [point] });
});
