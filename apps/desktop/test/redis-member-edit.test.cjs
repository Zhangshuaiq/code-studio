const test = require('node:test');
const assert = require('node:assert/strict');
const crypto = require('node:crypto');
const Redis = require('ioredis');
const { LocalConnectorRuntime } = require('../src/local-connector-runtime.cjs');
const { validateRedisMutation } = require('../src/redis-mutation.cjs');
test('member mutation rejects readonly/unconfirmed requests and invalid scores/references', () => {
  const input = { action: 'zset-create', key: 'key', member: 'member', score: '1.5', confirm: true };
  assert.throws(() => validateRedisMutation(input, true), /只读/);
  assert.throws(() => validateRedisMutation({ ...input, confirm: false }, false), /确认/);
  for (const score of ['NaN', 'Infinity', '1e999', '0x12', '', ' 1 ']) assert.throws(() => validateRedisMutation({ ...input, score }, false), /有限数字/);
  assert.throws(() => validateRedisMutation({ ...input, member: 'bad!', memberEncoding: 'base64' }, false), /编码/);
  assert.throws(() => validateRedisMutation({ ...input, action: 'zset-edit' }, false), /原始分数/);
  assert.equal(validateRedisMutation({ ...input, member: '', score: '-1e2' }, false).member.length, 0);
});
test('real Redis set/zset member CRUD preserves TTL and rejects stale/concurrent writes', { skip: process.env.RUN_REDIS_TESTS !== '1', timeout: 30000 }, async t => {
  const settings = { host: process.env.REDIS_HOST || '127.0.0.1', port: Number(process.env.REDIS_PORT || 6379), db: 0 };
  const secret = process.env.REDIS_PASSWORD || '';
  const client = new Redis({ ...settings, password: secret || undefined, lazyConnect: true, retryStrategy: () => null, maxRetriesPerRequest: 0 }); client.on('error', () => {});
  const prefix = 'code-studio-member-edit:' + crypto.randomUUID(); const keys = [prefix + ':set', prefix + ':zset'];
  t.after(async () => { try { if (client.status === 'ready') await client.del(...keys); } finally { client.disconnect(); } });
  await client.connect(); await client.sadd(keys[0], 'seed'); await client.zadd(keys[1], 0, 'seed'); await client.expire(keys[0], 60); await client.expire(keys[1], 60);
  const runtime = new LocalConnectorRuntime();
  const change = (key, input, extra = {}) => runtime.explore({ type: 'redis', settings }, secret, { readOnly: false, redisMutation: { key, confirm: true, ...input }, ...extra });
  const member = Buffer.from([0, 255]); const reference = { member: member.toString('base64'), memberEncoding: 'base64' };
  await change(keys[0], { action: 'set-create', ...reference }); assert.equal(await client.sismember(keys[0], member), 1);
  await assert.rejects(change(keys[0], { action: 'set-create', ...reference }), /已存在/);
  let checks = 0;
  await assert.rejects(change(keys[0], { action: 'set-delete', ...reference }, { authorizeRedisMutation: async () => { if (++checks === 2) await client.sadd(keys[0], 'concurrent'); } }), /并发/);
  assert.equal(await client.sismember(keys[0], member), 1); await change(keys[0], { action: 'set-delete', ...reference });
  assert.equal(await client.sismember(keys[0], member), 0); assert.ok(await client.ttl(keys[0]) > 0);
  await change(keys[1], { action: 'zset-create', ...reference, score: '1.5' });
  await assert.rejects(change(keys[1], { action: 'zset-create', ...reference, score: '9' }), /已存在/);
  await change(keys[1], { action: 'zset-edit', ...reference, score: '-2', expectedScore: '1.5' });
  assert.equal(await client.zscore(keys[1], member), '-2'); assert.ok(await client.ttl(keys[1]) > 0);
  await assert.rejects(change(keys[1], { action: 'zset-delete', ...reference, expectedScore: '1.5' }), /分数已改变/);
  checks = 0;
  await assert.rejects(change(keys[1], { action: 'zset-edit', ...reference, score: '9', expectedScore: '-2' }, { authorizeRedisMutation: async () => { if (++checks === 2) await client.zadd(keys[1], 3, member); } }), /并发/);
  assert.equal(await client.zscore(keys[1], member), '3');
  await change(keys[1], { action: 'zset-delete', ...reference, expectedScore: '3' }); assert.equal(await client.zscore(keys[1], member), null);
  checks = 0;
  await assert.rejects(change(keys[1], { action: 'zset-edit', member: 'seed', score: '2', expectedScore: '0' }, { authorizeRedisMutation: async () => { if (++checks === 2) throw new Error('提交前撤权'); } }), /提交前撤权/);
  assert.equal(await client.zscore(keys[1], 'seed'), '0');
});
