const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const os = require('node:os');
const path = require('node:path');
const { execFileSync } = require('node:child_process');
const comparison = require('../../../packages/code-intelligence/git-comparison.cjs');
const merge = require('../../../packages/code-intelligence/git-merge.cjs');
test('branch comparison and merge conflict resolution preserve HEAD, verify versions, and support continue/abort', async t => {
  const root = await fs.mkdtemp(path.join(os.tmpdir(), 'git-merge-test-'));
  t.after(() => fs.rm(root, { recursive: true, force: true }));
  const git = (...args) => execFileSync('git', ['-c', 'core.hooksPath=/dev/null', '-c', 'commit.gpgsign=false', ...args], { cwd: root, encoding: 'utf8' }).trim();
  git('init', '-b', 'main'); git('config', 'user.name', 'Fixture'); git('config', 'user.email', 'fixture@example.invalid');
  await fs.writeFile(path.join(root, 'file.txt'), 'start\nbase\nend\n'); git('add', '.'); git('commit', '-m', 'base');
  git('checkout', '-b', 'feature'); await fs.writeFile(path.join(root, 'file.txt'), 'start\ntheirs\nend\n'); git('commit', '-am', 'theirs');
  git('checkout', 'main'); await fs.writeFile(path.join(root, 'file.txt'), 'start\nours\nend\n'); git('commit', '-am', 'ours');
  const head = git('rev-parse', 'HEAD');
  const list = await comparison.compareBranches(root, 'main', 'feature'); assert.equal(list.items[0].path, 'file.txt');
  const file = await comparison.branchFile(root, 'main', 'feature', 'file.txt'); assert.match(file.before, /ours/); assert.match(file.after, /theirs/); assert.equal(git('rev-parse', 'HEAD'), head);
  await assert.rejects(comparison.branchFile(root, 'main', 'feature', '../outside'), /路径/);
  await assert.rejects(comparison.workingFile(root, '.Git/config'), /路径/);
  await assert.rejects(comparison.compareBranches(root, '--help', 'feature'), /版本/);
  assert.equal((await merge.merge(root, 'start', 'feature')).conflicts[0], 'file.txt');
  const detail = await merge.detail(root, 'file.txt'); assert.equal(detail.hunks.length, 1); assert.match(detail.suggestions.ours, /start\nours\nend/); assert.match(detail.suggestions.theirs, /theirs/);
  await assert.rejects(merge.resolve(root, { path: 'file.txt', version: 'stale', resolution: 'ours' }), /已变化/);
  await fs.appendFile(path.join(root, 'file.txt'), 'external change\n');
  await assert.rejects(merge.resolve(root, { path: 'file.txt', version: detail.version, resolution: 'ours' }), /已变化/);
  await merge.merge(root, 'abort'); assert.equal(git('rev-parse', 'HEAD'), head); assert.equal((await merge.status(root)).mergeInProgress, false);
  await merge.merge(root, 'start', 'feature'); const fresh = await merge.detail(root, 'file.txt');
  await assert.rejects(merge.merge(root, 'continue'), /未解决/);
  await merge.resolve(root, { path: 'file.txt', version: fresh.version, resolution: 'manual', content: fresh.suggestions.both });
  assert.deepEqual((await merge.status(root)).conflicts, []);
  assert.equal((await merge.merge(root, 'continue')).mergeInProgress, false);
  assert.notEqual(git('rev-parse', 'HEAD'), head); assert.match(await fs.readFile(path.join(root, 'file.txt'), 'utf8'), /ours\ntheirs/);
  await fs.writeFile(path.join(root, 'dirty.txt'), 'unsaved work'); await assert.rejects(merge.merge(root, 'start', 'feature'), /当前修改/);
});
